const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

function comparableProductName(value: string): string {
  return value.normalize("NFC").trim().replace(/\s+/g, " ").toLocaleLowerCase(
    "es-MX",
  );
}

/**
 * Resuelve cada renglón al producto canónico. Un UUID inválido o inexistente
 * puede recuperarse únicamente con el nombre exacto que devolvió
 * buscar_producto. Si un UUID válido apunta a un nombre distinto se rechaza:
 * jamás se cambia silenciosamente lo que se va a cobrar/preparar.
 */
export function resolveOrderItemsAgainstProducts(
  items: RequestedOrderItemInput[],
  products: ProductoEncontrado[],
): Array<
  RequestedOrderItemInput & { product_id: string; product_name: string }
> {
  return items.map((item) => {
    const requestedId = typeof item?.product_id === "string"
      ? item.product_id.trim()
      : "";
    const requestedName = typeof item?.product_name === "string"
      ? item.product_name.trim()
      : "";
    const byId = requestedId
      ? products.find((product) => product.id === requestedId)
      : undefined;
    const byName = requestedName
      ? products.find((product) =>
        comparableProductName(product.name) ===
          comparableProductName(requestedName)
      )
      : undefined;

    if (
      byId && requestedName &&
      comparableProductName(byId.name) !== comparableProductName(requestedName)
    ) {
      throw new OrderValidationError(
        `El identificador y el nombre del producto no coinciden: ${requestedName}. Vuelve a usar exactamente el resultado de buscar_producto.`,
      );
    }
    const product = byId ?? byName;
    if (!product) {
      const reference = requestedName || requestedId || "sin identificador";
      throw new OrderValidationError(
        `Producto no disponible: ${reference}. Vuelve a llamar buscar_producto y copia también product_name.`,
      );
    }
    return {
      ...item,
      product_id: product.id,
      product_name: product.name,
    };
  });
}

function mapBranchProducts(rows: any[] | null): ProductoEncontrado[] {
  return (rows ?? [])
    .filter((row: any) => row.is_available)
    .map((row: any) => ({
      id: row.products.id,
      name: row.products.name,
      price: Number(row.price),
      pack_size: extraerPackSize(row.products.name, row.products.description),
      requires_adult_confirmation: requiresAdultConfirmation(
        row.products.name,
        row.products.categories?.name,
      ),
    }));
}

async function resolveBranchOrderItems(
  supabase: any,
  branchId: string,
  items: RequestedOrderItemInput[],
): Promise<{
  items: Array<
    RequestedOrderItemInput & { product_id: string; product_name: string }
  >;
  products: ProductoEncontrado[];
}> {
  if (!Array.isArray(items) || items.length === 0 || items.length > 100) {
    throw new OrderValidationError("El pedido no tiene productos válidos");
  }
  for (const item of items) {
    const idValid = typeof item?.product_id === "string" &&
      UUID_PATTERN.test(item.product_id);
    const nameValid = typeof item?.product_name === "string" &&
      item.product_name.trim().length > 0 && item.product_name.length <= 240;
    if (!idValid && !nameValid) {
      throw new OrderValidationError(
        "Cada producto requiere un UUID válido o el product_name exacto devuelto por buscar_producto.",
      );
    }
  }

  const select =
    "price, is_available, products!inner(id, name, description, categories(name))";
  const validIds = [
    ...new Set(
      items
        .map((item) => item.product_id)
        .filter((id): id is string =>
          typeof id === "string" && UUID_PATTERN.test(id)
        ),
    ),
  ];
  const exactNames = [
    ...new Set(
      items
        .map((item) => item.product_name?.trim())
        .filter((name): name is string => Boolean(name)),
    ),
  ];
  const rows: any[] = [];

  if (validIds.length > 0) {
    const { data, error } = await supabase.from("branch_products")
      .select(select)
      .eq("branch_id", branchId)
      .in("product_id", validIds);
    if (error) throw error;
    rows.push(...(data ?? []));
  }
  if (exactNames.length > 0) {
    const { data, error } = await supabase.from("branch_products")
      .select(select)
      .eq("branch_id", branchId)
      .in("products.name", exactNames);
    if (error) throw error;
    rows.push(...(data ?? []));
  }

  const byId = new Map<string, ProductoEncontrado>();
  for (const product of mapBranchProducts(rows)) byId.set(product.id, product);
  const products = [...byId.values()];
  return {
    items: resolveOrderItemsAgainstProducts(items, products),
    products,
  };
}

function extraerPackSize(
  name: string,
  description: string | null,
): number | null {
  const texto = `${name} ${description ?? ""}`;
  const orden = texto.match(/orden de (\d+)/i);
  if (orden) return parseInt(orden[1], 10);
  if (/individual/i.test(texto)) return 1;
  return null;
}

/**
 * Traduce lo que pidió el cliente (piezas/unidades habladas) a unidades
 * cobrables del catálogo. El cálculo vive fuera del LLM para que
 * "8 individuales" nunca se convierta en "máximo 1", y para que una orden
 * de 3 se cobre una sola vez, no tres.
 */
export function buildOrderQuoteFromProducts(
  requestedItems: RequestedOrderItemInput[],
  products: ProductoEncontrado[],
  options: { adult_confirmed?: boolean } = {},
): OrderQuote {
  if (!Array.isArray(requestedItems) || requestedItems.length === 0) {
    throw new OrderValidationError("El pedido no tiene productos");
  }
  if (requestedItems.length > 100) {
    throw new OrderValidationError("Productos o cantidades inválidos");
  }

  const lines: QuotedOrderLine[] = [];
  let total = 0;
  for (const item of requestedItems) {
    if (
      !item || typeof item.product_id !== "string" ||
      item.product_id.length > 64 ||
      !Number.isInteger(item.requested_quantity) ||
      item.requested_quantity < 1 || item.requested_quantity > 100
    ) {
      throw new OrderValidationError("Productos o cantidades inválidos");
    }
    const product = products.find((candidate) =>
      candidate.id === item.product_id
    );
    if (!product) {
      throw new OrderValidationError(
        `Producto no disponible: ${item.product_id}`,
      );
    }

    if (
      product.requires_adult_confirmation === true &&
      options.adult_confirmed !== true
    ) {
      throw new OrderValidationError(
        `Antes de cotizar ${product.name}, confirma de forma explícita que quien recibe el pedido es mayor de edad.`,
      );
    }

    if (
      item.tortilla !== undefined && item.tortilla !== "maiz" &&
      item.tortilla !== "harina"
    ) {
      throw new OrderValidationError(
        `Tortilla inválida para ${product.name}: elige maíz o harina.`,
      );
    }
    const requiresTortilla = /\btacos?\b/i.test(product.name);
    if (requiresTortilla && !item.tortilla) {
      throw new OrderValidationError(
        `Antes de continuar, confirma si ${product.name} va con tortilla de maíz o harina.`,
      );
    }
    // Los modelos a veces copian el último enum de tortilla a todos los
    // renglones del tool call. El backend conserva la elección solo donde
    // semánticamente aplica; una Coca-Cola o una pizza nunca carga tortilla.
    const tortilla = requiresTortilla ? item.tortilla ?? null : null;

    const packSize = product.pack_size;
    if (packSize !== null && (!Number.isInteger(packSize) || packSize < 1)) {
      throw new OrderValidationError(
        `Presentación inválida para ${product.name}`,
      );
    }
    if (packSize && packSize > 1 && item.requested_quantity % packSize !== 0) {
      const lower = Math.floor(item.requested_quantity / packSize) * packSize;
      const upper = Math.ceil(item.requested_quantity / packSize) * packSize;
      const options = lower >= packSize ? `${lower} o ${upper}` : String(upper);
      throw new OrderValidationError(
        `${product.name} solo se vende en órdenes de ${packSize} piezas. ` +
          `Pediste ${item.requested_quantity}; puedes pedir ${options}.`,
      );
    }

    const quantity = packSize && packSize > 1
      ? item.requested_quantity / packSize
      : item.requested_quantity;
    const price = Number(product.price);
    const lineTotal = Math.round(price * quantity * 100) / 100;
    total = Math.round((total + lineTotal) * 100) / 100;
    lines.push({
      product_id: product.id,
      name: product.name,
      price,
      requested_quantity: item.requested_quantity,
      pack_size: packSize,
      quantity,
      tortilla,
      requires_adult_confirmation: product.requires_adult_confirmation === true,
      line_total: lineTotal,
    });
  }

  return {
    items: lines.map((line) => ({
      product_id: line.product_id,
      quantity: line.quantity,
      ...(line.tortilla ? { tortilla: line.tortilla } : {}),
    })),
    lines,
    total,
  };
}

export function requiresAdultConfirmation(
  productName: string,
  categoryName: string | null | undefined,
): boolean {
  if (!/^(cervezas|licores y cocktails)$/i.test(categoryName ?? "")) {
    return false;
  }
  return !/(?:\bsin\s+alcohol\b|\b0[.,]0\b)/i.test(productName);
}

/**
 * Búsqueda real de productos disponibles en una sucursal, compartida por el
 * agente de voz (buscar-producto/index.ts) y el de WhatsApp
 * (whatsapp-agent-core.ts) — antes cada uno traía su propia copia de esta
 * consulta (mismo texto, dos archivos) y las dos comparaban el query del
 * cliente SOLO contra `products.name`. Bug real confirmado 4-sep-2026: un
 * cliente pidió "una pizza" y el agente dijo que no había disponible, pese a
 * que sí existe un producto real ("Quesobich de Queso", categoría "Pizza
 * Quesobich") que es literalmente una pizza — la palabra "pizza" solo vive en
 * su `description` y en el nombre de su categoría, nunca en `products.name`,
 * así que la búsqueda angosta no lo encontraba. Ahora un token hace match si
 * aparece en el name, la description, la categoría, O cualquier alias de
 * `products.search_keywords` (columna sembrada a mano para ~250 productos
 * reales el 4-sep-2026) — todos los tokens siguen siendo obligatorios (AND),
 * solo se amplió EN QUÉ campo puede aparecer cada uno.
 */
export async function buscarProductosCore(
  supabase: any,
  {
    branchId,
    restaurantId,
    query,
  }: {
    branchId: string;
    restaurantId: string;
    query: string;
  },
): Promise<ProductoEncontrado[]> {
  const tokens = tokenizeForProductSearch(query);

  const { data: rows, error } = await supabase
    .from("branch_products")
    .select(
      "price, is_available, products!inner(id, name, description, restaurant_id, search_keywords, categories(name))",
    )
    .eq("branch_id", branchId)
    .eq("is_available", true)
    .eq("products.restaurant_id", restaurantId)
    .limit(400);
  if (error) throw error;

  const coincide = (r: any) => {
    const producto = r.products;
    const textoPlano = [
      producto.name,
      producto.description,
      producto.categories?.name,
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase();
    const alias: string[] = producto.search_keywords ?? [];
    return tokens.every(
      (t) =>
        textoPlano.includes(t) ||
        alias.some((a) => a.toLowerCase().includes(t)),
    );
  };

  return (rows ?? [])
    .filter(coincide)
    .slice(0, 8)
    .map((r: any) => ({
      id: r.products.id,
      name: r.products.name,
      price: r.price,
      pack_size: extraerPackSize(r.products.name, r.products.description),
      requires_adult_confirmation: requiresAdultConfirmation(
        r.products.name,
        r.products.categories?.name,
      ),
    }));
}

