/**
 * Contrato único para pedidos reales y simulados. Mantenerlo puro permite que
 * la vista previa pruebe exactamente las mismas entradas sin escribir datos.
 */
export function validateCreateOrderPayload(
  rawPayload: CreateOrderPayload,
): CreateOrderPayload {
  if (
    !rawPayload || typeof rawPayload !== "object" || Array.isArray(rawPayload)
  ) {
    throw new OrderValidationError("Payload inválido");
  }
  if (
    (!(typeof rawPayload.branch_slug === "string" &&
      rawPayload.branch_slug.trim()) &&
      !(typeof rawPayload.branch_name === "string" &&
        rawPayload.branch_name.trim())) ||
    typeof rawPayload.customer_name !== "string" ||
    !rawPayload.customer_name.trim() ||
    typeof rawPayload.customer_phone !== "string" ||
    !rawPayload.customer_phone.trim()
  ) {
    throw new OrderValidationError(
      "branch_slug (o branch_name), customer_name y customer_phone son requeridos",
    );
  }
  if (
    rawPayload.customer_name.trim().length > 160 ||
    rawPayload.customer_phone.length > 64 ||
    invalidOptionalString(rawPayload.branch_slug, 100) ||
    invalidOptionalString(rawPayload.branch_name, 160) ||
    invalidOptionalString(rawPayload.customer_address, 1000) ||
    invalidOptionalString(rawPayload.notes, 2000) ||
    invalidOptionalString(rawPayload.conversation_id, 200) ||
    invalidOptionalString(rawPayload.call_transcript, 20000) ||
    invalidOptionalString(rawPayload.call_recording_url, 2000)
  ) {
    throw new OrderValidationError(
      "Uno o más campos exceden el tamaño permitido",
    );
  }
  if (
    rawPayload.idempotency_key !== undefined &&
    (typeof rawPayload.idempotency_key !== "string" ||
      !rawPayload.idempotency_key.trim() ||
      rawPayload.idempotency_key.length > 200)
  ) {
    throw new OrderValidationError("idempotency_key inválido");
  }
  if (
    rawPayload.adult_confirmed !== undefined &&
    typeof rawPayload.adult_confirmed !== "boolean"
  ) {
    throw new OrderValidationError("adult_confirmed debe ser booleano");
  }
  const agentOrder = rawPayload.source === "voice" ||
    rawPayload.source === "whatsapp";
  if (
    agentOrder &&
    (typeof rawPayload.customer_address !== "string" ||
      !rawPayload.customer_address.trim())
  ) {
    throw new OrderValidationError(
      "La dirección completa de entrega es requerida",
    );
  }
  if (
    (agentOrder && rawPayload.payment_method !== "efectivo" &&
      rawPayload.payment_method !== "tarjeta") ||
    (!agentOrder && rawPayload.payment_method !== undefined &&
      rawPayload.payment_method !== "efectivo" &&
      rawPayload.payment_method !== "tarjeta")
  ) {
    throw new OrderValidationError(
      "La forma de pago debe ser efectivo o tarjeta",
    );
  }
  const voicePhone = rawPayload.source === "voice"
    ? canonicalizeMexicanPhone(rawPayload.customer_phone)
    : null;
  if (rawPayload.source === "voice" && !voicePhone) {
    throw new OrderValidationError(
      "Teléfono inválido: confirma exactamente 10 dígitos y vuelve a leerlos al cliente en grupos 3-3-4.",
    );
  }
  const payload: CreateOrderPayload = {
    ...rawPayload,
    branch_slug: rawPayload.branch_slug?.trim() || undefined,
    branch_name: rawPayload.branch_name?.trim() || undefined,
    customer_name: rawPayload.customer_name.trim(),
    customer_phone: voicePhone ?? normalizePhone(rawPayload.customer_phone),
    customer_address: rawPayload.customer_address?.trim(),
  };
  if (!Array.isArray(payload.items) || payload.items.length === 0) {
    throw new OrderValidationError("El pedido no tiene productos");
  }
  if (
    payload.items.length > 100 ||
    payload.items.some(
      (item) => {
        if (
          !item || typeof item !== "object" || Array.isArray(item) ||
          (item.product_id !== undefined &&
            (typeof item.product_id !== "string" ||
              item.product_id.length > 64)) ||
          (item.product_name !== undefined &&
            (typeof item.product_name !== "string" ||
              item.product_name.length > 240)) ||
          (!(typeof item.product_id === "string" &&
            UUID_PATTERN.test(item.product_id)) &&
            !(typeof item.product_name === "string" &&
              item.product_name.trim())) ||
          (item.tortilla !== undefined && item.tortilla !== "maiz" &&
            item.tortilla !== "harina")
        ) return true;
        const hasQuantity = item.quantity !== undefined;
        const hasRequested = item.requested_quantity !== undefined;
        if (hasQuantity === hasRequested) return true;
        const value = hasRequested ? item.requested_quantity : item.quantity;
        return !Number.isInteger(value) || (value as number) < 1 ||
          (value as number) > 100;
      },
    )
  ) {
    throw new OrderValidationError("Productos o cantidades inválidos");
  }
  const validRequestedComplements = new Set<RequestedComplement>([
    "salsa_habanero",
    "crema_ajo",
  ]);
  const validDefaultComplements = new Set<DefaultComplement>(
    DEFAULT_COMPLEMENTS,
  );
  if (
    (payload.requested_complements !== undefined &&
      (!Array.isArray(payload.requested_complements) ||
        payload.requested_complements.length > validRequestedComplements.size ||
        payload.requested_complements.some((item) =>
          !validRequestedComplements.has(item)
        ))) ||
    (payload.omit_default_complements !== undefined &&
      (!Array.isArray(payload.omit_default_complements) ||
        payload.omit_default_complements.length >
          validDefaultComplements.size ||
        payload.omit_default_complements.some((item) =>
          !validDefaultComplements.has(item)
        )))
  ) {
    throw new OrderValidationError("Complementos inválidos");
  }
  return payload;
}

export async function prepareCreateOrder(
  supabase: any,
  rawPayload: CreateOrderPayload,
) {
  const payload = validateCreateOrderPayload(rawPayload);

  const branchQuery = supabase
    .from("branches")
    .select("id, name, is_active, restaurant_id");
  const { data: branch, error: branchError } = await (
    payload.branch_slug
      ? branchQuery.eq("slug", payload.branch_slug)
      : branchQuery.eq("name", payload.branch_name)
  ).maybeSingle();

  if (branchError) throw branchError;
  if (!branch || !branch.is_active) {
    throw new OrderValidationError(
      `Sucursal '${
        payload.branch_slug ?? payload.branch_name
      }' no encontrada o inactiva`,
    );
  }

  // Precio y disponibilidad REALES de esta sucursal — verificados contra
  // fotos reales del menú de cada una, distintos de verdad entre sucursales
  // (branch_products), no el precio plano de `products` (catálogo maestro
  // de nombres/categorías compartido, ya no la fuente de precio/verdad).
  const resolved = await resolveBranchOrderItems(
    supabase,
    branch.id,
    payload.items.map((item) => ({
      product_id: item.product_id,
      product_name: item.product_name,
      // La resolución solo necesita identidad; los callers web antiguos usan
      // quantity y se conserva abajo desde el payload original.
      requested_quantity: Number.isInteger(item.requested_quantity)
        ? item.requested_quantity as number
        : 1,
      tortilla: item.tortilla,
    })),
  );

  const orderItems: {
    id: string;
    name: string;
    price: number;
    quantity: number;
    tortilla?: TortillaChoice;
  }[] = [];
  let total = 0;
  let containsAlcohol = false;

  for (const [index, inputItem] of payload.items.entries()) {
    const canonicalItem = resolved.items[index];
    const product = resolved.products.find((candidate) =>
      candidate.id === canonicalItem.product_id
    )!;
    const requiresAdult = product.requires_adult_confirmation === true;
    if (requiresAdult) containsAlcohol = true;
    if (
      requiresAdult &&
      (payload.source === "voice" || payload.source === "whatsapp") &&
      payload.adult_confirmed !== true
    ) {
      throw new OrderValidationError(
        `Antes de crear el pedido con ${product.name}, confirma de forma explícita que quien recibe el pedido es mayor de edad.`,
      );
    }
    const requestedPieces = Number.isInteger(inputItem.requested_quantity);
    const item = buildOrderQuoteFromProducts(
      [{
        product_id: canonicalItem.product_id,
        product_name: canonicalItem.product_name,
        requested_quantity: (requestedPieces
          ? inputItem.requested_quantity
          : inputItem.quantity) as number,
        tortilla: inputItem.tortilla,
      }],
      [{
        id: product.id,
        name: product.name,
        price: product.price,
        // quantity ya representa unidades del catálogo, no piezas.
        pack_size: requestedPieces ? product.pack_size : null,
        requires_adult_confirmation: requiresAdult,
      }],
      {
        adult_confirmed: payload.adult_confirmed ||
          (!requestedPieces && payload.source !== "voice" &&
            payload.source !== "whatsapp"),
      },
    ).items[0];
    if (!Number.isInteger(item.quantity) || item.quantity <= 0) {
      throw new OrderValidationError(
        `Cantidad inválida para ${product.name}`,
      );
    }
    const lineTotal = Math.round(product.price * item.quantity * 100) / 100;
    total = Math.round((total + lineTotal) * 100) / 100;
    orderItems.push({
      id: product.id,
      name: product.name,
      price: product.price,
      quantity: item.quantity,
      ...(item.tortilla ? { tortilla: item.tortilla } : {}),
    });
  }

  return { payload, branch, orderItems, total, containsAlcohol };
}

export async function createOrderCore(
  supabase: any,
  rawPayload: CreateOrderPayload,
) {
  const { payload, branch, orderItems, total, containsAlcohol } =
    await prepareCreateOrder(supabase, rawPayload);

  // Customer memory: ensure identity before inserting the order. The database
  // increments order_count only if the idempotent insert actually creates a row.
  const customer = await upsertCustomer(
    supabase,
    branch.restaurant_id,
    payload.customer_phone,
    payload.customer_name,
    payload.customer_address,
  );

  // Bug crítico real confirmado en la auditoría del 3-sep-2026 ("haz múltiples
  // pruebas... rómpelo"): cuando un mensaje del cliente confundía al LLM
  // (input agresivo, fuera de tema, o simplemente "¿ya quedó mi pedido?"), el
  // loop de tool-use de WhatsApp se quedaba sin turnos disponibles DESPUÉS de
  // que crear_pedido ya había tenido éxito, y el fallback genérico
  // ("se me complicó procesar tu pedido") hacía que el cliente insistiera —
  // el siguiente mensaje disparaba una SEGUNDA llamada real a crear_pedido
  // con los mismos productos, creando un pedido duplicado real en `orders`
  // (verificado: 2 filas reales, mismo teléfono/sucursal/items/total,
  // segundos de diferencia). Se corrige el mensaje de fallback engañoso en
  // whatsapp-agent-core.ts, PERO la protección real y a prueba de canal
  // (voz, WhatsApp, web, cualquiera futuro) vive aquí: si ya existe un
  // pedido "pending" MUY reciente (mismo teléfono, misma sucursal, mismos
  // items exactos), se devuelve ESE pedido en vez de insertar uno nuevo —
  // nunca dos filas reales por una sola intención real de pedido.
  const itemsOrdenados = [...orderItems].sort((a, b) =>
    JSON.stringify(a).localeCompare(JSON.stringify(b))
  );
  const complementNotes = buildComplementNotes(
    payload.notes,
    [...new Set(payload.requested_complements ?? [])].sort(),
    [...new Set(payload.omit_default_complements ?? [])].sort(),
  );
  const finalNotes = containsAlcohol
    ? [
      complementNotes,
      "Recepción de alcohol: mayoría de edad confirmada por el cliente.",
    ].join("\n")
    : complementNotes;
  const dedupeFingerprint = await sha256Hex(
    JSON.stringify({
      restaurant_id: branch.restaurant_id,
      branch_id: branch.id,
      customer_name: payload.customer_name,
      customer_phone: payload.customer_phone,
      customer_address: payload.customer_address ?? null,
      payment_method: payload.payment_method ?? null,
      source: payload.source ?? "web",
      notes: finalNotes,
      total,
      items: itemsOrdenados.map((item) => ({
        id: item.id,
        name: item.name,
        price: item.price,
        quantity: item.quantity,
        tortilla: item.tortilla ?? null,
      })),
      requested_complements: [...(payload.requested_complements ?? [])].sort(),
      omit_default_complements: [...(payload.omit_default_complements ?? [])]
        .sort(),
    }),
  );
  const idempotencyKey = payload.idempotency_key
    ? await sha256Hex(`${branch.restaurant_id}:${payload.idempotency_key}`)
    : null;

  const { data: order, error: insertError } = await supabase.rpc(
    "create_order_idempotent",
    {
      p_order: {
        customer_name: payload.customer_name,
        customer_phone: payload.customer_phone,
        customer_address: payload.customer_address ?? null,
        customer_id: customer.id,
        restaurant_id: branch.restaurant_id,
        branch: branch.name,
        branch_id: branch.id,
        total,
        status: "pending",
        items: orderItems,
        source: payload.source ?? "web",
        call_transcript: payload.call_transcript ?? null,
        call_recording_url: payload.call_recording_url ?? null,
        notes: finalNotes,
        payment_method: payload.payment_method ?? null,
      },
      p_dedupe_fingerprint: dedupeFingerprint,
      p_idempotency_key: idempotencyKey,
    },
  );

  if (insertError?.code === "PT409") {
    throw new OrderConflictError(
      "Este intento de pedido ya fue procesado con datos diferentes. Revisa el pedido existente antes de crear otro.",
    );
  }
  if (insertError) throw insertError;

  return order;
}

async function upsertCustomer(
  supabase: any,
  restaurantId: string,
  phone: string,
  name: string,
  address?: string,
) {
  const { data: existing, error: lookupError } = await supabase
    .from("customers")
    .select("id, name")
    .eq("restaurant_id", restaurantId)
    .eq("phone", phone)
    .maybeSingle();
  if (lookupError) throw lookupError;

  let customer;
  if (existing) {
    const { data: updated, error } = await supabase
      .from("customers")
      .update({
        name: existing.name ?? name, // never overwrite a known name with a possibly-misheard one
      })
      .eq("id", existing.id)
      .select()
      .single();
    if (error) throw error;
    customer = updated;
  } else {
    const { data: created, error } = await supabase
      .from("customers")
      .insert({ restaurant_id: restaurantId, phone, name, order_count: 0 })
      .select()
      .single();
    if (error) {
      // Dos pedidos reales casi simultáneos del mismo cliente nuevo (ej.
      // manda el mensaje dos veces seguidas por mala señal) pueden ambos
      // ver "no existe" y ambos intentar el INSERT — el UNIQUE real
      // (restaurant_id, phone) hace que el segundo truene con 23505 en vez
      // de crear un duplicado silencioso (correcto), pero antes eso se
      // propagaba como error genérico al cliente en vez de recuperarse.
      // Verificado con pruebas de carga concurrente el 3-sep-2026.
      if (error.code === "23505") {
        const { data: existingRace, error: raceError } = await supabase
          .from("customers")
          .select("id, name")
          .eq("restaurant_id", restaurantId)
          .eq("phone", phone)
          .single();
        if (raceError) throw raceError;
        if (existingRace) {
          const { data: updated, error: updateError } = await supabase
            .from("customers")
            .update({
              name: existingRace.name ?? name,
            })
            .eq("id", existingRace.id)
            .select()
            .single();
          if (updateError) throw updateError;
          customer = updated;
        } else {
          throw error;
        }
      } else {
        throw error;
      }
    } else {
      customer = created;
    }
  }

  if (address) {
    const { count: addressCount, error: countError } = await supabase
      .from("customer_addresses")
      .select("id", { count: "exact", head: true })
      .eq("customer_id", customer.id);
    if (countError) throw countError;
    if (typeof addressCount !== "number") {
      throw new Error("No se pudo consultar las direcciones del cliente");
    }

    const { error: addressError } = await supabase
      .from("customer_addresses")
      .upsert(
        { customer_id: customer.id, address, is_default: addressCount === 0 },
        { onConflict: "customer_id,address", ignoreDuplicates: true },
      );
    if (addressError) throw addressError;
  }

  return customer;
}

export type CustomerTier = "BLACK" | "PLATINUM" | "GOLD" | "BLUE";

// Nota lista para inyectar tal cual en un prompt/tool-result: cuando el
// cliente es BLACK o PLATINUM el agente (voz o WhatsApp) debe saberlo y
// tratarlo con calidez extra/prioridad — pedido explícito de Javier, no
// dejar el tier calculado sin usar en el trato real.
export function vipNote(tier: CustomerTier | null): string | null {
  if (tier === "BLACK") {
    return "Es cliente BLACK — uno de los clientes de mayor consumo/frecuencia del restaurante (top 10%). Trátalo con calidez extra y dale prioridad.";
  }
  if (tier === "PLATINUM") {
    return "Es cliente PLATINUM — uno de los clientes más frecuentes/de mayor consumo del restaurante. Trátalo con calidez extra y dale prioridad.";
  }
  return null;
}

export function isOrderEligibleForRecommendations(status: unknown): boolean {
  return typeof status === "string" && [
    "pending",
    "preparando",
    "en_camino",
    "entregado",
    "completado",
  ].includes(status);
}

// Used by the voice agent's buscar_cliente Server Tool and by the WhatsApp
// webhook to greet a returning customer by name and offer their saved address
// before taking the order, per the requested flow: identify -> confirm/offer
// address -> take order -> recap what's included -> total -> wait time.
//
// Memoria real de cliente frecuente (no solo del último pedido): además del
// último pedido, agrega frequent_items (los productos más pedidos across
// TODO su historial real, contando cantidades reales de orders.items) y
// tier (BLACK/PLATINUM/GOLD/BLUE, mismos cortes de percentil que
// ClientesSection.tsx) calculado server-side vía la función SQL
// calc_customer_tier (ver supabase/migrations/20260903140000_customer_tier_percentile.sql)
// contra la distribución real de TODOS los clientes del restaurante, sin
// traer esa lista completa a este edge function.
export async function lookupCustomer(
  supabase: any,
  restaurantId: string,
  phone: string,
) {
  const { data: customer } = await supabase
    .from("customers")
    .select("id, name, order_count")
    .eq("restaurant_id", restaurantId)
    .eq("phone", normalizePhone(phone))
    .maybeSingle();

  if (!customer) {
    return { is_new: true as const };
  }

  const { data: addresses } = await supabase
    .from("customer_addresses")
    .select("address, label, is_default")
    .eq("customer_id", customer.id)
    .order("is_default", { ascending: false });

  // Todo el historial real de pedidos del cliente (no solo el último) —
  // ordenado desc, así allOrders[0] es también el último pedido y no hace
  // falta una segunda consulta aparte para eso.
  const { data: orderHistory } = await supabase
    .from("orders")
    .select("items, created_at, status")
    .eq("customer_id", customer.id)
    .order("created_at", { ascending: false });

  // Nunca sugerir como "lo de siempre" un pedido cancelado o con problema.
  // El filtro vuelve a aplicarse en memoria aunque en el futuro cambie la
  // consulta, para que esta regla de atención no dependa del LLM.
  const allOrders = (orderHistory ?? []).filter((order: any) =>
    isOrderEligibleForRecommendations(order.status)
  );
  const lastOrder = allOrders?.[0] ?? null;

  // frequent_items: ocurrencias reales (suma de cantidades) por producto,
  // contadas across TODO el historial real de orders.items de este
  // customer_id — no solo el último pedido. Con un solo pedido, coincide
  // con last_order_items (esperado).
  const conteoPorProducto = new Map<
    string,
    { name: string; quantity: number }
  >();
  for (const order of allOrders ?? []) {
    for (
      const item of (order.items ?? []) as {
        id?: string;
        name: string;
        quantity: number;
      }[]
    ) {
      const key = item.id ?? item.name;
      const actual = conteoPorProducto.get(key);
      if (actual) actual.quantity += item.quantity;
      else {
        conteoPorProducto.set(key, {
          name: item.name,
          quantity: item.quantity,
        });
      }
    }
  }
  const frequent_items = [...conteoPorProducto.values()]
    .sort((a, b) => b.quantity - a.quantity)
    .slice(0, 3);

  // Tier real por percentil, calculado en SQL (ver calc_customer_tier) —
  // si la función todavía no existe en la base (migración bloqueada por
  // Auto Mode, pendiente de aplicar a mano) o falla por cualquier motivo,
  // cae a tier: null en vez de romper la conversación.
  let tier: CustomerTier | null = null;
  const { data: tierResult, error: tierError } = await supabase.rpc(
    "calc_customer_tier",
    {
      p_restaurant_id: restaurantId,
      p_customer_id: customer.id,
    },
  );
  if (tierError) {
    console.error(
      "calc_customer_tier: no se pudo calcular, tier=null:",
      tierError,
    );
  } else {
    tier = (tierResult?.tier ?? null) as CustomerTier | null;
  }

  return {
    is_new: false as const,
    name: customer.name as string | null,
    order_count: customer.order_count as number,
    addresses: (addresses ?? []) as {
      address: string;
      label: string | null;
      is_default: boolean;
    }[],
    last_order_items: (lastOrder?.items ?? null) as
      | {
        name: string;
        quantity: number;
      }[]
      | null,
    frequent_items: frequent_items as { name: string; quantity: number }[],
    tier,
  };
}
